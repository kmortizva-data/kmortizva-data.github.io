def main() -> None:
    results = Results(SLUG, "TikTok: reclamación u opinión, y quién hizo el trabajo", COURSE)
    df = load(results)
    train, validation, test = split(df, results)

    stump = lone_question(train, validation, results)
    plain = candidates(train, validation, results)
    tuned = tune(train, validation, results)

    banner("6. El campeón, elegido en validación")
    Xv, yv = validation[FEATURES], validation.is_claim
    finalists = {"logistica": plain["logistica"], "bosque": tuned["bosque"],
                 "xgboost": tuned["xgboost"]}
    on_validation = {name: roc_auc_score(yv, model.predict_proba(Xv)[:, 1])
                     for name, model in finalists.items()}
    champion = max(on_validation, key=on_validation.get)
    for name, auc in on_validation.items():
        results.put(f"finalists.{name}_validation_auc", round(float(auc), 4))
    results.put("champion", champion)
    print(f"  campeón: {champion}")

    banner("7. La prueba, una sola vez, incluido el control")
    measure(stump, test[[LONE]], test.is_claim, results, "test.lone")
    for name, model in finalists.items():
        scores = measure(model, test[FEATURES], test.is_claim, results, f"test.{name}")
        print(f"  {name:11} AUC {scores['auc']:.4f}   exactitud {scores['accuracy']:.4f}")
    lone_accuracy = results.data["test"]["lone"]["accuracy"]
    print(f"  {'una pregunta':11} AUC {results.data['test']['lone']['auc']:.4f}   "
          f"exactitud {lone_accuracy:.4f}")

    banner("8. El veredicto")
    best = max(results.data["test"][name]["accuracy"] for name in finalists)
    results.put("verdict.lone_accuracy", lone_accuracy)
    results.put("verdict.best_model_accuracy", round(float(best), 4))
    results.put("verdict.gain_over_one_question", round(float(best - lone_accuracy), 4),
                "lo que aportan nueve variables y trescientos árboles sobre una pregunta")
    print(f"  una pregunta:      {lone_accuracy:.4f}")
    print(f"  el mejor modelo:   {best:.4f}")
    print(f"  lo que aportó todo lo demás: {best - lone_accuracy:+.4f}")

    banner("9. Figuras")
    figure_the_cut(df, results)
    figure_one_question(results)
    figure_importance(tuned["bosque"], results)
    figure_exceptions(train, results)
    for figure in sorted(FIGURES.glob("*.png")):
        print(f"  {figure.name}")

    results.write()


if __name__ == "__main__":
    main()
