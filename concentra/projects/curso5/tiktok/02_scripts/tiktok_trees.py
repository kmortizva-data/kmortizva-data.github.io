FIGURES = figures_dir(COURSE, SLUG)
SEED = 42

COUNTERS = ["video_view_count", "video_like_count", "video_share_count",
            "video_download_count", "video_comment_count"]
FEATURES = COUNTERS + ["video_duration_sec", "verified", "banned", "under_review"]
LONE = "video_view_count"          # the one column the control model is allowed to see

LABELS = {
    "video_view_count": "Visualizaciones", "video_like_count": "Me gusta",
    "video_share_count": "Compartidos", "video_download_count": "Descargas",
    "video_comment_count": "Comentarios", "video_duration_sec": "Duración",
    "verified": "Cuenta verificada", "banned": "Autor expulsado",
    "under_review": "Autor en revisión",
}


def load(results: Results) -> pd.DataFrame:
    banner("1. Los datos, y el objetivo que cambia respecto al Curso 4")
    df = pd.read_csv(dataset(SLUG))
    results.put("data.rows_raw", len(df), "filas en el CSV")
    results.put("data.rows_incomplete", int(df.isna().any(axis=1).sum()),
                "filas incompletas, las mismas 298 del Curso 2")

    df = df.dropna().copy()
    df["is_claim"] = df.claim_status.eq("claim").astype(int)
    df["verified"] = df.verified_status.eq("verified").astype(int)
    df["banned"] = df.author_ban_status.eq("banned").astype(int)
    df["under_review"] = df.author_ban_status.eq("under review").astype(int)

    results.put("data.rows_clean", len(df), "filas completas")
    results.put("data.claim_pct", round(100 * float(df.is_claim.mean()), 1),
                "porcentaje de reclamaciones")
    # The Course 4 target was verified_status, at 93.6 % against 6.4 %, so that project had
    # to downsample. This one is balanced by nature and needs nothing.
    results.put("data.needs_balancing", False,
                "¿hace falta equilibrar? En el Curso 4 sí, aquí no")

    views = df.groupby("claim_status").video_view_count
    results.put("signal.claim_mean_views", round(float(views.mean()["claim"]), 1))
    results.put("signal.opinion_mean_views", round(float(views.mean()["opinion"]), 1))
    results.put("signal.view_ratio",
                round(float(views.mean()["claim"] / views.mean()["opinion"]), 1),
                "cuántas veces más se ve una reclamación, el hallazgo del Curso 2")
    results.put("signal.opinion_max_views", int(views.max()["opinion"]),
                "la opinión más vista de todo el archivo")
    results.put("signal.claim_min_views", int(views.min()["claim"]),
                "la reclamación menos vista")
    return df


def split(df: pd.DataFrame, results: Results) -> tuple[pd.DataFrame, ...]:
    banner("2. Partición en tres, con la prueba apartada desde el principio")
    rest, test = train_test_split(df, test_size=0.20, random_state=SEED,
                                  stratify=df.is_claim)
    train, validation = train_test_split(rest, test_size=0.25, random_state=SEED,
                                         stratify=rest.is_claim)
    for name, part in [("train", train), ("validation", validation), ("test", test)]:
        results.put(f"split.{name}_rows", len(part))
    print(f"  entrenamiento {len(train)}   validación {len(validation)}   prueba {len(test)}")
    return train, validation, test


def lone_question(train, validation, results: Results) -> DecisionTreeClassifier:
    """The control: one cut, one column. Everything else is measured against this.

    Fitted before the real models on purpose. Deciding afterwards what counts as a good
    baseline is how a project talks itself into being impressed by its own result.
    """
    banner("3. El control: un árbol de UNA pregunta sobre UNA columna")
    stump = DecisionTreeClassifier(max_depth=1, random_state=SEED).fit(
        train[[LONE]], train.is_claim)
    cut = float(stump.tree_.threshold[0])
    results.put("lone.column", LONE)
    results.put("lone.threshold", round(cut, 1), "el corte que eligió, en visualizaciones")

    accuracy = accuracy_score(validation.is_claim, stump.predict(validation[[LONE]]))
    results.put("lone.validation_accuracy", round(float(accuracy), 4))
    print(f"  la regla entera: si el vídeo pasa de {cut:,.0f} visualizaciones, es "
          f"reclamación")
    print(f"  y con eso solo acierta el {100 * accuracy:.2f} % en validación")

    # How many videos in the whole file that one rule gets wrong, and who they are.
    wrong = ((train.claim_status.eq("opinion") & train[LONE].gt(cut)) |
             (train.claim_status.eq("claim") & train[LONE].le(cut)))
    results.put("lone.exceptions_train", int(wrong.sum()),
                "vídeos del entrenamiento que esa regla se salta")
    results.put("lone.exceptions_are_claims",
                int((wrong & train.claim_status.eq("claim")).sum()),
                "  de ellos, reclamaciones con pocas visualizaciones")
    return stump


def candidates(train, validation, results: Results) -> dict:
    banner("4. Los candidatos de verdad, con las nueve variables")
    X, y = train[FEATURES], train.is_claim
    Xv, yv = validation[FEATURES], validation.is_claim
    models = {
        "logistica": LogisticRegression(max_iter=3000),
        "arbol": DecisionTreeClassifier(random_state=SEED),
        "bosque": RandomForestClassifier(n_estimators=300, random_state=SEED, n_jobs=-1),
        "xgboost": XGBClassifier(n_estimators=300, max_depth=4, learning_rate=0.1,
                                 eval_metric="logloss", random_state=SEED, n_jobs=1),
    }
    for name, model in models.items():
        model.fit(X, y)
        auc = roc_auc_score(yv, model.predict_proba(Xv)[:, 1])
        accuracy = accuracy_score(yv, model.predict(Xv))
        results.put(f"candidates.{name}_auc", round(float(auc), 4))
        results.put(f"candidates.{name}_accuracy", round(float(accuracy), 4))
        print(f"  {name:11} AUC {auc:.4f}   exactitud {accuracy:.4f}")
    return models


def tune(train, validation, results: Results) -> dict:
    banner("5. Ajuste de perillas")
    X, y = train[FEATURES], train.is_claim
    Xv, yv = validation[FEATURES], validation.is_claim
    tuned = {}
    grids = {
        "bosque": (RandomForestClassifier(n_estimators=300, random_state=SEED, n_jobs=-1),
                   {"max_depth": [3, 5, 8, None], "min_samples_leaf": [1, 5, 20],
                    "max_features": ["sqrt", 0.5]}),
        "xgboost": (XGBClassifier(eval_metric="logloss", random_state=SEED, n_jobs=1),
                    {"max_depth": [2, 3, 5], "learning_rate": [0.05, 0.1],
                     "n_estimators": [200, 400]}),
    }
    for name, (estimator, grid) in grids.items():
        combinations = int(np.prod([len(v) for v in grid.values()]))
        started = time.perf_counter()
        search = GridSearchCV(estimator, grid, cv=4, scoring="roc_auc", n_jobs=-1).fit(X, y)
        elapsed = time.perf_counter() - started
        auc = roc_auc_score(yv, search.best_estimator_.predict_proba(Xv)[:, 1])
        results.put(f"tuning.{name}.combinations", combinations)
        results.put(f"tuning.{name}.seconds", round(elapsed, 1))
        results.put(f"tuning.{name}.best_params",
                    {k: str(v) for k, v in search.best_params_.items()})
        results.put(f"tuning.{name}.cv_auc", round(float(search.best_score_), 4))
        results.put(f"tuning.{name}.validation_auc", round(float(auc), 4))
        print(f"  {name:8} {combinations} combinaciones en {elapsed:4.0f} s   AUC {auc:.4f}")
        tuned[name] = search.best_estimator_
    return tuned


def measure(model, features, truth, results: Results, prefix: str) -> dict:
    probability = model.predict_proba(features)[:, 1]
    decision = (probability >= 0.5).astype(int)
    scores = {
        "accuracy": accuracy_score(truth, decision),
        "precision": precision_score(truth, decision, zero_division=0),
        "recall": recall_score(truth, decision),
        "f1": f1_score(truth, decision),
        "auc": roc_auc_score(truth, probability),
    }
    for name, value in scores.items():
        results.put(f"{prefix}.{name}", round(float(value), 4))
    return scores


