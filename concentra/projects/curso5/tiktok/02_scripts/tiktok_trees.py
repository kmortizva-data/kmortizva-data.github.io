"""TikTok, Course 5: classify a video as a claim or an opinion, and ask who did the work.

The obvious version of this project fits a random forest, reports 99.6 % and calls it a
success. This one fits the forest, reports the same number, and then spends the rest of its
time proving that **the algorithm contributed almost nothing**.

Run it:
    python projects/curso5/tiktok/02_scripts/tiktok_trees.py

Reads Kevin's CSV read-only, writes figures to 03_figures/ and every publishable number to
04_reports/model_results.json.

The control that makes the point: a decision tree of **one single question about one single
column** is fitted alongside the tuned forest. If the forest with nine variables and three
hundred trees cannot beat one question, then the performance was in the data before any
model touched it.

Course 2 already found that signal from the other side: a claim gets 101 times the views of
an opinion, and the two distributions barely overlap. This project is what that finding
looks like once you try to build on it.

And it ends somewhere uncomfortable. The data is synthetic, generated by TikTok for the
certificate, and the single threshold lands at 10,031 views while the most-watched opinion
in the whole file has 9,998. That is not a behaviour anyone discovered. It is the seam of
how the file was manufactured, and a model that scores 99.6 % on it has measured the
generator, not the platform.
"""

